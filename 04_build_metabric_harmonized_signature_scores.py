    require(len(physical) == N_EXPRESSION_GENES and all(re.fullmatch(r"ENTREZ_[1-9][0-9]*", name) for name in physical), "Extended-score expression schema differs")
    genes = [normalize_entrez(name) for name in physical]
    require(len(set(genes)) == N_EXPRESSION_GENES and set(genes) == set(plan["universe"]) | set(EXPECTED_MISSING), "Extended-score canonical gene axis differs")
    positions = {gene: position for position, gene in enumerate(genes)}
    rank_positions = np.array([positions[gene] for gene in plan["universe"]], dtype=np.int64)
    missing = np.zeros(N_EXPRESSION_GENES, dtype=np.int64)
    legacy = pd.read_csv(output / "results/01_harmonized_singscores_v1.csv.gz", dtype={"sampleId": str}, float_precision="round_trip").set_index("sampleId")
    legacy_positions = [(i, plan["references"][name]["score_id"]) for name, i in zip(plan["reference_order"], plan["reference_positions"]) if name in FROZEN_PROVENANCE["authorized_score_entities"]]
    legacy_maximum = 0.0
    legacy_comparisons = 0
    def rows():
        nonlocal legacy_maximum, legacy_comparisons
        seen = set()
        with pd.read_csv(expression, compression=compression, chunksize=args.chunk_size, dtype={"sampleId": str}, low_memory=False) as reader:
            for chunk in reader:
                require(chunk.columns.tolist() == header, "Expression columns changed during extended scoring")
                identifiers = check_sample_ids(chunk["sampleId"], seen)
                seen.update(identifiers)
                require(len(seen) <= N_SAMPLES, "Too many extended-score samples")
                values = chunk[physical].to_numpy(dtype=np.float64)
                require(not np.isinf(values).any(), "Infinite expression in extended-score source")
                missing[:] += np.isnan(values).sum(axis=0)
                ranked = values[:, rank_positions]
                require(np.isfinite(ranked).all(), "Missing expression inside the fixed universe")
                for identifier, values in zip(identifiers, ranked):
                    ranks, _, _ = min_ranks(values)
                    scores = calculate_programme_row(ranks, plan)
                    for column, score_id in legacy_positions:
                        difference = abs(float(scores[column]) - float(legacy.loc[identifier, score_id]))
                        require(difference <= 1e-12, "Extended-score engine changed a historical score")
                        legacy_maximum = max(legacy_maximum, difference)
                        legacy_comparisons += 1
                    yield identifier, scores
    results = output / "results"
    write_programme_definitions(output, plan)
    details = write_programme_score_stream(rows(), plan, results / "16_all_programme_scores_v2.csv.gz", results / "17_all_reference_scores_v2.csv.gz")
    require(details["samples"] == N_SAMPLES and details["sample_set_sha256"] == SAMPLE_SET_SHA256, "Extended-score sample scope differs")
    require({gene: int(n) for gene, n in zip(genes, missing) if n} == EXPECTED_MISSING, "Extended-score missingness differs")
    require(legacy_comparisons == 12190, "Historical compatibility comparison is incomplete")
    require(sha256(expression) == before and sha256(plan["catalogue_source"]) == CATALOGUE_SOURCE_SHA256, "Extended-score input changed")
    qc = [{"calculator_id": unit["calculator_id"], "score_column": unit["column_name"], "samples": N_SAMPLES, "positive_genes": len(unit["up"]), "negative_genes": len(unit["down"]), "minimum": float(details["minimum_by_calculator"][i]), "maximum": float(details["maximum_by_calculator"][i]), "clipping_applied": False} for i, unit in enumerate(plan["units"])]
    write_table(results / "18_all_score_quality_v2.csv", pd.DataFrame(qc))
    write_json(results / "19_programme_formula_self_tests_v2.json", formula_tests)
    write_json(results / "20_all_score_manifest_v2.json", {"version": EXTENDED_VERSION, "status": "COMPLETED_ALL_REGISTERED_SCORE_CONTRACTS_NOT_FROZEN", "script_sha256": sha256(Path(__file__).resolve()), "catalogue_source_file": plan["catalogue_source"].name, "catalogue_source_sha256": CATALOGUE_SOURCE_SHA256, "catalogue_source_executed_as_pipeline": False, "catalogue_outputs_required": False, "historical_compatibility_manifest": "manifest_v1.json", "samples": N_SAMPLES, "ranking_universe_genes": N_RANK_GENES, "ranking_universe_sha256": UNIVERSE_SHA256, "definition_labels_with_scores": 15805, "distinct_calculators": 15790, "generic_programme_profiles": 15784, "generic_programme_labels": 15793, "reference_labels": 15, "values_written": details["values_written"], "calculator_set_sha256": EXPECTED_CALCULATOR_SET_SHA256, "label_relation_sha256": EXPECTED_LABEL_RELATION_SHA256, "generic_calculator_set_sha256": EXPECTED_GENERIC_SET_SHA256, "reviewed_membership_relation_sha256": plan["membership_relation_sha256"], "historical_compatibility_values_compared": legacy_comparisons, "historical_compatibility_maximum_absolute_difference": legacy_maximum, "absolute_tolerance": 1e-12, "relative_tolerance": 0.0, "named_UP_DOWN_does_not_assign_risk_or_reverse_controls": True, "rank_ties": "MIN", "cohort_standardization": False, "clipping": False, "source_documentary_permission_flags_changed": False, "unscored_context_definitions": 110, "restricted_multiarm_definitions": 2, "empty_documentary_definitions": 3, "input_expression_sha256": before, "original_expression_byte_identity": before == EXPRESSION_SHA256, "historical816_programme_value_equivalence_rechecked": False, "clinical_or_outcome_files_read": [], "models_fitted": False, "new_predictor_inclusion_authorized": False, "main_SAP_changed": False, "source_memberships_changed": False, "predictive_validation_claimed": False})
