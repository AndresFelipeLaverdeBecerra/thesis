def coverage_and_overlap(tables: dict, universe: list[str]) -> tuple[pd.DataFrame, pd.DataFrame]:
    in_universe = set(universe)
    groups = {entity: set(group["mapped_human_entrez_current"])
              for entity, group in tables["membership_entrez_deduplicated_v1.csv"].groupby("Membership entity ID", sort=True)}
    scoring_entities = set(tables["future_scoring_specifications_v1.csv"]["entity_id"])
    coverage = []
    for entity, genes in groups.items():
        effective = genes & in_universe
        coverage.append({
            "entity_id": entity, "mapped_entrez_total": len(genes), "genes_in_rank_universe": len(effective),
            "fraction_of_mapped_in_rank_universe": len(effective) / len(genes),
            "genes_outside_rank_universe": "|".join(sorted(genes - in_universe, key=int)),
            "scoring_permitted": entity in scoring_entities,
        })
    overlaps = []
    for a, b in itertools.combinations(groups, 2):
        x, y = groups[a] & in_universe, groups[b] & in_universe
        overlaps.append({
            "entity_a": a, "entity_b": b, "a_in_rank_universe": len(x), "b_in_rank_universe": len(y),
            "intersection_in_rank_universe": len(x & y), "union_in_rank_universe": len(x | y),
            "jaccard_in_rank_universe": len(x & y) / len(x | y) if x | y else 0.0,
            "both_scored": a in scoring_entities and b in scoring_entities,
        })
                                                                              
    return pd.DataFrame(coverage), pd.DataFrame(overlaps)


def compare_reference(scores: pd.DataFrame, reference: Path) -> tuple[pd.DataFrame, dict]:
    raw_hash = sha256(reference)
    opener = gzip.open if compression_of(reference) else Path.open
    with opener(reference, mode="rb") as handle:
        data = handle.read(5 * 1024 * 1024 + 1)
    require(len(data) <= 5 * 1024 * 1024, "Reference score file unexpectedly large")
    require(hashlib.sha256(data).hexdigest() == REFERENCE_CSV_SHA256,
            "Reference is not the pinned, frozen phase-07 score table")
    ref = pd.read_csv(io.BytesIO(data), dtype={"sampleId": str}, float_precision="round_trip")
    ids = check_sample_ids(ref["sampleId"], set())
    require(set(ids) == set(scores["sampleId"]) and len(ids) == len(scores), "Reference sample set mismatch")
    require(set(ref.columns) == set(scores.columns), "Reference score columns mismatch")
    aligned = ref.set_index("sampleId").loc[scores["sampleId"]]
    rows = []
    for column in scores.columns[1:]:
        left = scores[column].to_numpy(dtype=np.float64)
        right = aligned[column].to_numpy(dtype=np.float64)
        require(np.isfinite(right).all(), f"Reference has nonfinite scores: {column}")
        difference = np.abs(left - right)
        rows.append({
            "specification_id": column, "samples_compared": len(left), "max_absolute_difference": difference.max(),
            "mean_absolute_difference": difference.mean(), "absolute_tolerance": REFERENCE_ATOL,
            "relative_tolerance": 0.0, "values_outside_tolerance": int((difference > REFERENCE_ATOL).sum()),
            "passed": bool((difference <= REFERENCE_ATOL).all()),
        })
    report = pd.DataFrame(rows)
    return report, {
        "file": reference.name, "sha256": raw_hash, "uncompressed_sha256": hashlib.sha256(data).hexdigest(),
        "absolute_tolerance": REFERENCE_ATOL, "relative_tolerance": 0.0,
        "values_compared": len(scores) * (len(scores.columns) - 1), "passed": bool(report["passed"].all()),
    }


def write_json(path: Path, value: dict) -> None:
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")


def write_table(path: Path, frame: pd.DataFrame) -> dict:
    data = csv_bytes(frame)
    if path.name.endswith(".gz"):
        with path.open("xb") as raw:
            with gzip.GzipFile(fileobj=raw, mode="wb", filename="", mtime=0, compresslevel=9) as handle:
                handle.write(data)
    else:
        with path.open("xb") as handle:
            handle.write(data)
    return {"sha256": sha256(path), "uncompressed_csv_sha256": hashlib.sha256(data).hexdigest(),
            "size_bytes": path.stat().st_size, "rows": len(frame)}


def reserve_output(path: Path) -> Path:
    require(not path.is_symlink() and not path.exists(), "Output must be a NEW path; overwrite is not supported")
    output = path.resolve()
    for ancestor in (output, *output.parents):
        require(not (ancestor / "FREEZE_RECORD.json").exists(), f"Refusing to write inside frozen phase: {ancestor}")
    output.mkdir(parents=True, exist_ok=False)
    return output


