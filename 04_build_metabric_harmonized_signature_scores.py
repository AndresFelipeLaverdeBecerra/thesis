"""Reproduce METABRIC V1 harmonized signature scores from the output of script 03.

This is the fourth, standalone source file in the thesis repository. It starts
AFTER identifier mapping: the reviewed Entrez memberships and readiness decisions
are embedded below as readable CSV text with their original SHA-256 hashes. It
does not download authorities, redo literature extraction, resolve ambiguous
probes, or reproduce every historical phase-01/04/05/06 file. Upstream audit
hashes identify those separate frozen stages. No additional definition file is
required at runtime; the expression matrix remains an external input.

Scope
-----
* Recheck the canonical 1,219-sample / 20,192-gene matrix from script 03.
* Reconstruct the numerically sorted 20,182-gene universe by the frozen
  no-missing-expression rule; require its exact frozen SHA-256 and the ten
  original exclusions with their original missing-value counts (12 cells).
* Export the 577 deduplicated entity-gene memberships derived upstream from
  585 documentary rows. These are NOT 577 distinct genes across all entities.
* Retain 18 signature records and nine auxiliary control sets. Only Kim49
  (22 UP, 27 DOWN) and the nine control sets are scored: 491 effective
  entity/arm/gene memberships, ten scores per sample. No patient risk groups,
  clinical/outcome groups, thresholds, or final panel are created here.
* Quayle and Cheng stay blocked; the other incomplete signatures remain pending.
  A control whose NAME ends in DN is still scored as a separate named set:
  it is not negated and is not combined with its corresponding UP set.
* Kim is a HARMONIZED singscore, NOT a reconstruction of the original Kim
  reference-mean formula, a recurrence probability, or a clinical classifier.
* Read no clinical or outcome files, fit no models, and never alter inputs,
  existing output directories, or frozen canonical phases.

Method (the contract already frozen in phase 07)
-----------------------------------------------
Rank genes independently within each sample, ascending, ties='min'. For a set
of k genes from N=20,182, centered_score=(mean_rank-(k+1)/2)/(N-k)-0.5.
Kim = centered_score(UP) + centered_score(DOWN using N+1-ascending_rank).
The DOWN operation is the frozen reversal, not a fresh rank(-expression).
No imputation, cohort z-scoring, reference-mean fitting, gene-variance filter,
normalization, or outcome-guided gene selection is performed. Ties are retained;
scores are never clipped. The frozen range checks are applied to this cohort.
Reference: https://doi.org/10.1186/s12859-018-2435-4
Frozen documentation: Bioconductor singscore 1.32.0.

Requirements and examples
-------------------------
Python >=3.10, NumPy and pandas. Frozen execution: Python 3.11.10,
numpy==2.1.1, pandas==2.2.3. To use that numerical environment:
    python -m pip install numpy==2.1.1 pandas==2.2.3

Local self-check only (does not read the expression matrix or write files):
    python 04_build_metabric_harmonized_signature_scores.py --self-test

Rebuild into a NEW directory, anywhere (no Slurm or Hypatia paths required):
    python 04_build_metabric_harmonized_signature_scores.py \
        --expression modeling_data/transcriptomics_v1/metabric_expression_entrez_median.csv.gz \
        --output-dir reproduced_signature_scores_v1

Optional subsequent comparison against the actual frozen phase-07 score file:
    python 04_build_metabric_harmonized_signature_scores.py \
        --expression modeling_data/transcriptomics_v1/metabric_expression_entrez_median.csv.gz \
        --output-dir reproduced_signature_scores_v1_checked \
        --reference-scores path/to/01_harmonized_singscores_v1.csv.gz

The reference is checked against a pinned decompressed-file hash, then compared
by sampleId and score column, with fixed absolute tolerance 1e-12 and rtol=0.
It is never used to compute or tune the scores. No patient-level reference
scores or sample IDs are embedded in this public source file.

Re-creating script-03 gzip output may change its byte hash (gzip header/time),
even if its values are identical. By default, record that mismatch and enforce
the full cohort/identifier/missingness contract; do NOT claim input identity
from those structural checks. --strict-expression-hash requires the original
compressed bytes. Numerical equivalence requires the optional reference check
or a match to the pinned uncompressed score-output hash. Neither is evidence
of clinical validity. The real-matrix reproduction test is a separate step.

Outputs: definitions/ (reviewed CSV snapshots plus their provenance), results/
(seven phase-07-style tables, entity catalog, recalculated coverage/overlap,
rank QC, universe list, optional reference comparison, manifest), RUN_STATE.json.
The definition CSVs retain historical phase-05/06 flags such as scores=NO;
08_entity_catalog_v1.csv and the run manifest describe the present computation.
Gzip uses mtime=0 and no filename header. Manifests record input hashes and
software; these new runs are NOT automatically declared FROZEN.
"""

