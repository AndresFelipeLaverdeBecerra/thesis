def min_ranks(values: np.ndarray) -> tuple[np.ndarray, int, int]:
    """Phase-07 algorithm: one-based ascending ranks, tied values get minimum rank."""
    values = np.asarray(values, dtype=np.float64)
    require(values.ndim == 1 and len(values) > 0 and np.isfinite(values).all(),
            "Ranking needs a nonempty, finite one-dimensional vector")
    order = np.argsort(values, kind="mergesort")
    sorted_values = values[order]
    starts = np.empty(len(values), dtype=bool)
    starts[0] = True
    starts[1:] = sorted_values[1:] != sorted_values[:-1]
    start_positions = np.flatnonzero(starts)
    sorted_ranks = start_positions[np.cumsum(starts) - 1] + 1
    ranks = np.empty(len(values), dtype=np.float64)
    ranks[order] = sorted_ranks
    group_sizes = np.diff(np.r_[start_positions, len(values)])
    return ranks, int(group_sizes[group_sizes > 1].sum()), int(group_sizes.max())


def centered_set_score(ranks: np.ndarray, indices: np.ndarray) -> float:
    n_genes, set_size = len(ranks), len(indices)
    require(0 < set_size < n_genes, "Gene-set size must be between 1 and N-1")
    minimum_mean_rank = (set_size + 1.0) / 2.0
    return float((ranks[indices].mean() - minimum_mean_rank) / (n_genes - set_size) - 0.5)


def formula_self_tests() -> pd.DataFrame:
    values = np.arange(1.0, 11.0)
    ranks, tied, maximum = min_ranks(values)
    tied_ranks, tied_genes, tied_max = min_ranks(np.array([1.0, 2.0, 2.0, 4.0]))
    tests = {
        "ascending_min_ranks": np.array_equal(ranks, values),
        "no_ties": tied == 0 and maximum == 1,
        "top_two_up_is_positive_half": centered_set_score(ranks, np.array([8, 9])) == 0.5,
        "bottom_two_up_is_negative_half": centered_set_score(ranks, np.array([0, 1])) == -0.5,
        "bottom_two_down_is_positive_half": centered_set_score(11.0 - ranks, np.array([0, 1])) == 0.5,
        "ties_min_exact": np.array_equal(tied_ranks, np.array([1.0, 2.0, 2.0, 4.0])),
        "tie_diagnostics_exact": tied_genes == 2 and tied_max == 2,
        "monotone_invariance": np.array_equal(min_ranks(values * 3.5 + 7.0)[0], ranks),
    }
    require(all(tests.values()), f"Formula self-tests failed: {tests}")
    return pd.DataFrame([{"test": key, "passed": bool(value)} for key, value in tests.items()])


def build_memberships(tables: dict, universe: list[str]) -> tuple[dict, pd.DataFrame, pd.DataFrame]:
    universe_set = set(universe)
    position = {gene: i for i, gene in enumerate(universe)}
    membership = tables["membership_entrez_deduplicated_v1.csv"]
    calculated_flags = membership["mapped_human_entrez_current"].isin(universe_set).map({True: "YES", False: "NO"})
    require(calculated_flags.equals(membership["in_metabric_rank_universe"]),
            "Frozen membership coverage disagrees with reconstructed universe")
    entities, effective_rows, qc_rows = {}, [], []
    for spec in tables["future_scoring_specifications_v1.csv"].to_dict("records"):
        entity = spec["entity_id"]
        group = membership[membership["Membership entity ID"] == entity]
        if entity == KIM:
            require(spec["scoring_method"] == "SIGNED_SINGSCORE", "Kim scoring method changed")
            up = sorted(group.loc[group["Dirección/rol publicado"] == "UP", "mapped_human_entrez_current"], key=int)
            down = sorted(group.loc[group["Dirección/rol publicado"] == "DOWN", "mapped_human_entrez_current"], key=int)
            require(len(up) == 22 and len(down) == 27 and set(up + down) <= universe_set,
                    "Kim arm size or eligibility changed")
        else:
            require(spec["scoring_method"] == "SINGLE_SET_SINGSCORE", "Control scoring method changed")
            up = sorted(set(group["mapped_human_entrez_current"]) & universe_set, key=int)
            down = []
        require(0 < len(up) < len(universe), f"Invalid effective size: {entity}")
        entities[entity] = {
            "specification_id": spec["specification_id"], "method": spec["scoring_method"],
            "up": np.array([position[gene] for gene in up], dtype=np.int64),
            "down": np.array([position[gene] for gene in down], dtype=np.int64),
        }
        for arm, genes in (("UP", up), ("DOWN", down)):
            for gene in genes:
                effective_rows.append({
                    "specification_id": spec["specification_id"], "entity_id": entity,
                    "arm": arm, "entrez_id": gene, "rank_universe_position_zero_based": position[gene],
                })
        qc_rows.append({
            "specification_id": spec["specification_id"], "entity_id": entity,
            "scoring_method": spec["scoring_method"], "mapped_entrez_total": len(group),
            "up_genes_in_rank_universe": len(up), "down_genes_in_rank_universe": len(down),
            "effective_scoring_genes": len(up) + len(down), "rank_universe_genes": len(universe),
            "score_range_theoretical": "[-1,1]" if down else "[-0.5,0.5]",
        })
    effective = pd.DataFrame(effective_rows)
    entity_qc = pd.DataFrame(qc_rows)
    require(len(effective) == 491, "Effective membership must have 491 rows across ten entities")
    for filename, frame in (("05_scoring_membership_snapshot_v1.csv", effective), ("02_scoring_entity_qc_v1.csv", entity_qc)):
        require(hashlib.sha256(csv_bytes(frame)).hexdigest() == FROZEN_PROVENANCE["phase07_output_hashes"][filename],
                f"Reconstructed definition differs from frozen phase 07: {filename}")
    return entities, effective, entity_qc


def score_sample(values: np.ndarray, entities: dict) -> tuple[dict, int, int]:
    ranks, tied, maximum = min_ranks(values)
    result = {}
    for meta in entities.values():
        value = centered_set_score(ranks, meta["up"])
        if len(meta["down"]):
            value += centered_set_score((len(ranks) + 1.0) - ranks, meta["down"])
        result[meta["specification_id"]] = value
    return result, tied, maximum


def check_sample_ids(series: pd.Series, seen: set[str]) -> list[str]:
    require(not series.isna().any(), "Missing sampleId")
    ids = series.astype(str).str.strip().tolist()
    require(all(ids), "Blank sampleId")
    require(len(ids) == len(set(ids)) and not seen.intersection(ids), "Duplicate sampleId")
    return ids


def compute_expression(expression: Path, tables: dict, chunk_size: int) -> tuple[dict, dict]:
    header, compression = csv_header(expression)
    physical = header[1:]
    require(len(physical) == N_EXPRESSION_GENES, "Expected 20,192 gene columns plus sampleId")
    require(all(re.fullmatch(r"ENTREZ_[1-9][0-9]*", name) for name in physical),
            "Gene columns must be ENTREZ_<positive integer>, as produced by script 03")
    genes = [normalize_entrez(name) for name in physical]
    require(len(set(genes)) == N_EXPRESSION_GENES, "Duplicate normalized gene IDs")
    require(set(EXPECTED_MISSING) <= set(genes), "A frozen excluded gene is absent from expression")
    universe = sorted(set(genes) - set(EXPECTED_MISSING), key=int)
    require(len(universe) == N_RANK_GENES and text_sha256(list_text(universe)) == UNIVERSE_SHA256,
            "Expression identifiers do not reconstruct the exact 20,182-gene frozen universe")
    entities, effective, entity_qc = build_memberships(tables, universe)
    gene_position = {gene: i for i, gene in enumerate(genes)}
    rank_positions = np.array([gene_position[gene] for gene in universe], dtype=np.int64)
    missing_counts = np.zeros(len(genes), dtype=np.int64)
    score_rows, sample_rows, seen = [], [], set()
    with pd.read_csv(expression, compression=compression, chunksize=chunk_size,
                     dtype={"sampleId": str}, low_memory=False) as reader:
        for chunk in reader:
            require(chunk.columns.tolist() == header, "Expression columns changed during reading")
            ids = check_sample_ids(chunk["sampleId"], seen)
            seen.update(ids)
            require(len(seen) <= N_SAMPLES, "More than 1,219 samples")
            values = chunk[physical].to_numpy(dtype=np.float64)
            require(not np.isinf(values).any(), "Infinite expression value (not a permitted missing value)")
            missing_counts += np.isnan(values).sum(axis=0)
            ranked_values = values[:, rank_positions]
            require(np.isfinite(ranked_values).all(), "Missing/nonfinite value inside the frozen universe")
            for sample_id, row in zip(ids, ranked_values):
                calculated, tied, maximum = score_sample(row, entities)
                score_rows.append({"sampleId": sample_id, **calculated})
                sample_rows.append({
                    "sampleId": sample_id, "rank_universe_genes": N_RANK_GENES,
                    "genes_participating_in_expression_ties": tied,
                    "maximum_expression_tie_size": maximum, "all_expression_finite": "YES",
                })
    require(len(seen) == len(score_rows) == N_SAMPLES, "Expected exactly 1,219 unique samples")
    observed_missing = {gene: int(n) for gene, n in zip(genes, missing_counts) if n}
    require(observed_missing == EXPECTED_MISSING,
            f"Missingness differs from frozen V1; do not silently change the universe: {observed_missing}")
    rebuilt = sorted((gene for gene, n in zip(genes, missing_counts) if n == 0), key=int)
    require(rebuilt == universe, "Data-derived no-missing universe differs from frozen V1")
    scores = pd.DataFrame(score_rows)
    ids = scores["sampleId"].tolist()
    require(text_sha256(list_text(sorted(ids))) == SAMPLE_SET_SHA256,
            "Sample identities do not match the frozen cohort, despite the sample count")
    columns = [meta["specification_id"] for meta in entities.values()]
    require(scores.columns.tolist() == ["sampleId", *columns], "Unexpected score columns or order")
    require(np.isfinite(scores[columns].to_numpy()).all(), "Nonfinite score")
    for entity, meta in entities.items():
        lower, upper = (-1.0, 1.0) if entity == KIM else (-0.5, 0.5)
        values = scores[meta["specification_id"]]
        require(values.between(lower, upper, inclusive="both").all(), f"Score outside frozen range: {entity}")
        require(values.nunique() > 1, f"Constant score: {entity}")
    rank_qc = pd.DataFrame({
        "GENE_COLUMN": physical, "Entrez_Gene_Id": genes,
        "N_MISSING_1219": missing_counts, "IN_METABRIC_RANK_UNIVERSE_V1": missing_counts == 0,
    })
    outputs = {
        "01_harmonized_singscores_v1.csv.gz": scores,
        "02_scoring_entity_qc_v1.csv": entity_qc,
        "03_sample_ranking_qc_v1.csv": pd.DataFrame(sample_rows),
        "05_scoring_membership_snapshot_v1.csv": effective,
        "11_rank_universe_qc_v1.csv": rank_qc,
    }
    contract = {
        "universe": universe, "samples": len(scores), "score_columns": len(columns),
        "observed_missing_counts": observed_missing,
        "sample_set_sha256": text_sha256(list_text(sorted(ids))),
        "sample_order_sha256": text_sha256(list_text(ids)),
        "sample_order_matches_frozen": text_sha256(list_text(ids)) == SAMPLE_ORDER_SHA256,
    }
    return outputs, contract


def score_distributions(scores: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for column in scores.columns[1:]:
        values = scores[column]
        q = values.quantile([0.0, 0.25, 0.5, 0.75, 1.0])
        rows.append({
            "specification_id": column, "n": len(values), "missing": int(values.isna().sum()),
            "minimum": q.loc[0.0], "q1": q.loc[0.25], "median": q.loc[0.5],
            "mean": values.mean(), "q3": q.loc[0.75], "maximum": q.loc[1.0],
            "standard_deviation": values.std(ddof=1), "unique_values": values.nunique(),
        })
    return pd.DataFrame(rows)


