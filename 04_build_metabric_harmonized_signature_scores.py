def calculate_programme_row(ranks, plan):
    require(len(ranks) == N_RANK_GENES and np.isfinite(ranks).all(), "Programme ranking vector differs")
    sums = np.add.reduceat(ranks[plan["flat_positive_indices"]], plan["positive_starts"])
    sizes = plan["positive_counts"]
    result = (sums / sizes - (sizes + 1.0) / 2.0) / (N_RANK_GENES - sizes) - 0.5
    for column, indices in plan["signed_units"]:
        result[column] += centered_set_score(N_RANK_GENES + 1.0 - ranks, indices)
    require(result.shape == (15790,) and np.isfinite(result).all(), "Incomplete or nonfinite programme score vector")
    return result


def programme_formula_self_tests(plan):
    maximum = 0.0
    comparisons = 0
    n = N_RANK_GENES
    fixtures = [np.arange(n), np.arange(n - 1, -1, -1), np.array([(i * 43 + 17) % n // 11 for i in range(n)])]
    for values in fixtures:
        ranks, _, _ = min_ranks(values)
        ordered = sorted(values.tolist())
        oracle = [bisect.bisect_left(ordered, int(value)) + 1 for value in values]
        require(np.array_equal(ranks, oracle), "Independent minimum-rank oracle differs")
        actual = calculate_programme_row(ranks, plan)
        for column, unit in enumerate(plan["units"]):
            def exact(indices, reverse=False):
                size = len(indices)
                total = sum(n + 1 - oracle[int(i)] if reverse else oracle[int(i)] for i in indices)
                return (fractions.Fraction(total, size) - fractions.Fraction(size + 1, 2)) / (n - size) - fractions.Fraction(1, 2)
            expected = exact(unit["up"])
            if len(unit["down"]):
                expected += exact(unit["down"], True)
            error = abs(actual[column] - float(expected))
            require(error <= 1e-12, "Programme score differs from the independent exact arithmetic oracle")
            maximum = max(maximum, error)
            comparisons += 1
    require(comparisons == 47370, "Incomplete programme formula self-test")
    return {"status": "PASS_SYNTHETIC_MATH_ONLY", "samples": 3, "genes_per_sample": n, "calculators": 15790, "comparisons": comparisons, "maximum_absolute_error": maximum, "absolute_tolerance": 1e-12, "rank_oracle": "INDEPENDENT_SORT_AND_BISECT_LEFT", "score_oracle": "EXACT_RATIONAL_ARITHMETIC", "patient_values_read": False, "predictive_validation_claimed": False}


