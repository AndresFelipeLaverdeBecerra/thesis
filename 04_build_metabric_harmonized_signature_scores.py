def write_programme_score_stream(rows, plan, score_path, reference_path):
    columns = [unit["column_name"] for unit in plan["units"]]
    reference_columns = [plan["references"][name]["score_id"] for name in plan["reference_order"]]
    seen = set()
    minimum = np.full(15790, np.inf)
    maximum = np.full(15790, -np.inf)
    count = 0
    with score_path.open("xb") as score_raw, reference_path.open("xb") as reference_raw:
        with gzip.GzipFile(fileobj=score_raw, mode="wb", filename="", mtime=0) as score_gzip, gzip.GzipFile(fileobj=reference_raw, mode="wb", filename="", mtime=0) as reference_gzip:
            with io.TextIOWrapper(score_gzip, encoding="utf-8", newline="") as score_text, io.TextIOWrapper(reference_gzip, encoding="utf-8", newline="") as reference_text:
                writer = csv.writer(score_text, lineterminator="\n")
                reference_writer = csv.writer(reference_text, lineterminator="\n")
                writer.writerow(["sampleId"] + columns)
                reference_writer.writerow(["sampleId"] + reference_columns)
                for identifier, scores in rows:
                    require(identifier and identifier not in seen, "Duplicated or empty programme sample identifier")
                    require(np.shape(scores) == (15790,) and np.isfinite(scores).all(), "Invalid programme output row")
                    writer.writerow([identifier] + [format(float(value), ".17g") for value in scores])
                    reference_writer.writerow([identifier] + [format(float(scores[i]), ".17g") for i in plan["reference_positions"]])
                    seen.add(identifier)
                    minimum = np.minimum(minimum, scores)
                    maximum = np.maximum(maximum, scores)
                    count += 1
    require(count > 0, "No programme score rows were written")
    return {"samples": count, "sample_set_sha256": text_sha256(list_text(sorted(seen))), "distinct_score_columns": 15790, "values_written": count * 15790, "reference_columns": 15, "minimum_by_calculator": minimum, "maximum_by_calculator": maximum}


def compute_extended_scores(args, output, plan, formula_tests):
    expression = args.expression.resolve(strict=True)
