def require(condition: bool, message: str) -> None:
    """Use explicit checks (not assert), so python -O cannot disable safety."""
    if not condition:
        raise ValueError(message)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def text_sha256(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def list_text(values: list[str]) -> str:
    return "\n".join(values) + "\n"


def normalize_entrez(value: object) -> str:
    text = str(value).strip().removeprefix("ENTREZ_")
    require(bool(re.fullmatch(r"[1-9][0-9]*", text)), f"Invalid Entrez ID: {value!r}")
    return text


def csv_bytes(frame: pd.DataFrame) -> bytes:
    return frame.to_csv(index=False, float_format="%.17g", lineterminator="\n").encode("utf-8")


def compression_of(path: Path) -> str | None:
    with path.open("rb") as handle:
        return "gzip" if handle.read(2) == b"\x1f\x8b" else None


def csv_header(path: Path) -> tuple[list[str], str | None]:
    compression = compression_of(path)
    opener = gzip.open if compression else Path.open
    with opener(path, mode="rt", encoding="utf-8", newline="") as handle:
        header = next(csv.reader(handle), [])
    require(bool(header) and header[0] == "sampleId", "First CSV column must be sampleId")
    require(len(header) == len(set(header)), "Duplicate raw CSV headers (checked before pandas)")
    return header, compression


