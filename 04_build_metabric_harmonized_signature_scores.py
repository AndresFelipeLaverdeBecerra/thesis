def sorted_line_digest(lines):
    return hashlib.sha256("".join(line + "\n" for line in sorted(lines)).encode("utf-8")).hexdigest()


def load_catalogue_source(path):
    require(path.is_file() and not path.is_symlink(), "The unchanged step05 source is required beside step04")
    require(sha256(path) == CATALOGUE_SOURCE_SHA256, "Step05 source differs from the reviewed definition registry")
    specification = importlib.util.spec_from_file_location("metabric_reviewed_gene_set_definitions", str(path))
    require(specification is not None and specification.loader is not None, "Cannot load the step05 definition registry")
    module = importlib.util.module_from_spec(specification)
    old_bytecode_setting = sys.dont_write_bytecode
    try:
        sys.dont_write_bytecode = True
        specification.loader.exec_module(module)
    finally:
        sys.dont_write_bytecode = old_bytecode_setting
    module.verify_embedded_definitions()
    require(sha256(path) == CATALOGUE_SOURCE_SHA256, "Step05 changed while loading definitions")
    return module


def programme_descriptor(unit, universe):
    negative = unit["down"]
    return {
        "operation": "SIGNED_SUM_OF_CENTERED_MEAN_RANKS" if len(negative) else "ASCENDING_CENTERED_MEAN_RANK",
        "universe_sha256": UNIVERSE_SHA256,
        "ties": "MIN",
        "down_rank_rule": "N_PLUS_1_MINUS_ASCENDING_MIN_RANK" if len(negative) else "NONE",
        "positive_entrez": [universe[int(position)] for position in unit["up"]],
        "negative_entrez": [universe[int(position)] for position in negative],
        "clipping": False,
        "cohort_standardization_in_the_score": False,
    }


def programme_calculator_id(definition):
    encoded = json.dumps(definition, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return "score:" + hashlib.sha256(encoded).hexdigest()


