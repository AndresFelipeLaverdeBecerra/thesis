def refresh_output_checksums(output):
    paths = sorted(path for path in output.rglob("*") if path.is_file() and path.name not in {"RUN_STATE.json", "sha256sums.txt"})
    text = "".join(sha256(path) + "  " + path.relative_to(output).as_posix() + "\n" for path in paths)
    (output / "sha256sums.txt").write_text(text, encoding="utf-8", newline="")


def cli() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Compute reviewed reference and programme scores from step03 expression and fixed gene-set definitions.")
    parser.add_argument("--expression", type=Path, help="External sampleId x ENTREZ_* CSV or gzip CSV from script 03")
    parser.add_argument("--output-dir", type=Path, help="New output directory (must not already exist)")
    parser.add_argument("--chunk-size", type=int, default=64, help="Samples per expression chunk (default: 64)")
    parser.add_argument("--reference-scores", type=Path, help="Optional actual frozen phase-07 score CSV(.gz), for comparison only")
    parser.add_argument("--strict-expression-hash", action="store_true", help="Require the original compressed expression SHA-256")
    parser.add_argument("--catalogue-source", type=Path, default=Path(__file__).resolve().with_name(CATALOGUE_FILENAME), help="Reviewed step05 source next to this script; its pipeline is not executed")
    parser.add_argument("--historical-only", action="store_true", help="Reproduce the original ten scores only, without loading the expanded definition registry")
    parser.add_argument("--self-test", action="store_true", help="Check historical formulas and all 47,370 expanded synthetic comparisons; no patient input or result files")
    parser.add_argument("--version", action="version", version=EXTENDED_VERSION)
    args = parser.parse_args()
    if args.chunk_size < 1:
        parser.error("--chunk-size must be positive")
    if args.self_test:
        if args.expression or args.output_dir or args.reference_scores or args.strict_expression_hash:
            parser.error("--self-test is standalone; omit input/output/reference arguments")
    elif args.expression is None or args.output_dir is None:
        parser.error("--expression and --output-dir are required unless --self-test is used")
    return args


def main() -> int:
    args = cli()
    output = None
    try:
        tables = load_definitions()
        tests = formula_self_tests()
        programme_plan = None
        extended_tests = None
        if not args.historical_only:
            programme_plan = build_programme_plan(args.catalogue_source.resolve(), tables)
            extended_tests = programme_formula_self_tests(programme_plan)
        if args.self_test:
            print("[OK] All embedded definition hashes verified")
            print("[OK] 18 signatures, nine controls, 577 deduplicated memberships, ten permitted scores")
            print(tests.to_string(index=False))
            if extended_tests is not None:
                print(json.dumps(extended_tests, indent=2))
            print("[NOTE] No real expression data read; this is not the canonical reproduction test")
            return 0
        output = reserve_output(args.output_dir)
        write_json(output / "RUN_STATE.json", {"status": "RUNNING", "version": EXTENDED_VERSION, "historical_only": args.historical_only})
        execute(args, tables, tests, output)
        if programme_plan is not None:
            compute_extended_scores(args, output, programme_plan, extended_tests)
        refresh_output_checksums(output)
        write_json(output / "RUN_STATE.json", {
            "status": "COMPLETED_NOT_FROZEN", "version": EXTENDED_VERSION, "historical_only": args.historical_only,
            "completed_at_utc": datetime.now(timezone.utc).isoformat(),
        })
        return 0
    except Exception as error:
        if output is not None:
            write_json(output / "RUN_STATE.json", {"status": "FAILED", "version": EXTENDED_VERSION, "error": str(error)})
        print(f"[ERROR] {error}", file=sys.stderr)
        return 1


